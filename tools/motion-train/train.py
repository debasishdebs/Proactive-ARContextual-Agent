#!/usr/bin/env python3
"""Train the decision tree for TreeMotionModel from labelled motion_features.csv files.

  train.py <csv>... [--out TrainedMotionModel.kt] [--logistic]

Rows within 3 s after a label change and NONE / NOT_WORN rows are dropped. SITTING, EATING -> STILL;
GLANCING, CHORES -> HEAD_MOVING; WALKING -> WALKING. Leave-one-file-out validation (leave-one-out over
contiguous blocks when only one file is given). Numbers and enum names only.
"""
import argparse
import csv
import datetime
import sys

FEATURES = ["gyro_max", "gyro_mean", "gyro_rms", "above_on_frac", "acc_var", "step_hz", "rot_rad"]
CLASSES = ["STILL", "HEAD_MOVING", "WALKING"]
LABEL_CLASS = {"SITTING": 0, "EATING": 0, "GLANCING": 1, "CHORES": 1, "WALKING": 2}
SETTLE_MS = 3000


def load(path):
    """Returns (X, y) for one file after dropping settle windows and unusable labels."""
    xs, ys = [], []
    prev_label, switch_t = None, None
    with open(path, newline="") as fh:
        for r in csv.DictReader(fh):
            try:
                t = int(r["t_ms"])
                label = r["label"]
                x = [float(r[f]) for f in FEATURES]
            except (KeyError, ValueError):
                continue
            if label != prev_label:
                if prev_label is not None:
                    switch_t = t
                prev_label = label
            if switch_t is not None and t - switch_t < SETTLE_MS:
                continue
            if label not in LABEL_CLASS:
                continue
            xs.append(x)
            ys.append(LABEL_CLASS[label])
    return xs, ys


def blocks(ys, n=5):
    """Fallback folds for a single file: contiguous blocks."""
    size = max(1, len(ys) // n)
    return [list(range(i, min(len(ys), i + size))) for i in range(0, len(ys), size)]


def kotlin(tree, model_id):
    t = tree.tree_
    leaf = [0] * t.node_count
    for i in range(t.node_count):
        v = t.value[i][0]
        leaf[i] = max(range(len(v)), key=lambda k: v[k])
    # sklearn class indices follow sorted(classes_); map back to [STILL, HEAD_MOVING, WALKING].
    leaf = [int(tree.classes_[c]) for c in leaf]
    ints = lambda a: "intArrayOf(" + ", ".join(str(int(x)) for x in a) + ")"
    floats = lambda a: "floatArrayOf(" + ", ".join(f"{float(x):.6g}f" for x in a) + ")"
    return (
        "// Generated by tools/motion-train/train.py. Do not edit by hand.\n"
        "package com.rokid.context.glasses.capture.motion.model\n\n"
        "object TrainedMotionModel {\n"
        f'    val model = TreeMotionModel("{model_id}",\n'
        f"        {ints(t.feature)},\n"
        f"        {floats(t.threshold)},\n"
        f"        {ints(t.children_left)},\n"
        f"        {ints(t.children_right)},\n"
        f"        {ints(leaf)})\n"
        "}\n"
    )


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv", nargs="+")
    ap.add_argument("--out", default="TrainedMotionModel.kt")
    ap.add_argument("--logistic", action="store_true", help="print logistic-regression weights instead of writing a tree")
    a = ap.parse_args(argv)
    try:
        import numpy as np
        from sklearn.linear_model import LogisticRegression
        from sklearn.metrics import confusion_matrix
        from sklearn.tree import DecisionTreeClassifier
    except ImportError:
        sys.exit("error: scikit-learn and numpy are required (pip install scikit-learn)")

    files = [load(p) for p in a.csv]
    X = np.array([x for f in files for x in f[0]])
    y = np.array([c for f in files for c in f[1]])
    if len(y) == 0:
        sys.exit("error: no usable rows after filtering")
    print(f"rows={len(y)} " + " ".join(f"{CLASSES[k]}={int((y == k).sum())}" for k in range(3)))

    def make():
        if a.logistic:
            return LogisticRegression(max_iter=1000, class_weight="balanced")
        return DecisionTreeClassifier(max_depth=4, min_samples_leaf=20, class_weight="balanced", random_state=0)

    # Validation folds: one per file, or contiguous blocks if there is a single file.
    sizes = [len(f[1]) for f in files]
    if len(files) > 1:
        folds, o = [], 0
        for s in sizes:
            folds.append(list(range(o, o + s)))
            o += s
    else:
        folds = blocks(list(y))
    pred = np.full(len(y), -1)
    for te in folds:
        mask = np.ones(len(y), dtype=bool)
        mask[te] = False
        tr = np.flatnonzero(mask)
        if len(set(y[tr])) < 2:
            continue
        m = make().fit(X[tr], y[tr])
        pred[te] = m.predict(X[te])
    ok = pred >= 0
    if ok.any():
        print(f"leave-one-out accuracy={float((pred[ok] == y[ok]).mean()):.3f} folds={len(folds)}")
        print("confusion matrix (rows=true, cols=pred) order=" + ",".join(CLASSES))
        for row in confusion_matrix(y[ok], pred[ok], labels=[0, 1, 2]):
            print(" ".join(f"{int(v):4d}" for v in row))
    else:
        print("leave-one-out accuracy=na")

    model = make().fit(X, y)
    if a.logistic:
        for ci, cls in enumerate(model.classes_):
            print(CLASSES[int(cls)] + " " + " ".join(f"{f}={w:.4f}" for f, w in zip(FEATURES, model.coef_[ci])) + f" bias={model.intercept_[ci]:.4f}")
        return 0
    with open(a.out, "w") as fh:
        fh.write(kotlin(model, "tree-" + datetime.date.today().strftime("%Y%m%d")))
    print(f"wrote {a.out} nodes={model.tree_.node_count} depth={model.get_depth()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
